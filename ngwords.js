// ------------------------------------------------------------
//  誤検知を防ぐための「安全な言葉」
// ------------------------------------------------------------
//  ふつうの日本語なのに、上のリストの一部を含んでしまうものです。
//  判定の前にここに書いた言葉を取り除くので、誤ってブロックされません。
//  例：「〜ばかり」は「ばか」を含みますが、悪口ではありません。

export const SAFE_WORDS = [
  "ばかり", "ばかげ", "ばからし", "ばかばかしい",
  "くそまじめ", "くそ真面目",
  "はげしい", "激しい", "はげます", "励ま",
  "でぶつ",
];

// ------------------------------------------------------------
//  判定のしくみ
// ------------------------------------------------------------

/** カタカナをひらがなに直す */
function kataToHira(s) {
  return s.replace(/[ァ-ヶ]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) - 0x60)
  );
}

/**
 * 比べやすい形に整える。
 *  ・全角の英数字を半角に
 *  ・英字は小文字に
 *  ・カタカナをひらがなに
 *  ・空白や記号を取り除く（「し ね」「し*ね」のような崩しに備える）
 */
function normalize(s) {
  let t = String(s ?? "")
    .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) =>
      String.fromCharCode(c.charCodeAt(0) - 0xfee0)
    )
    .toLowerCase();
  t = kataToHira(t);
  t = t.replace(/[\s!-\/:-@\[-`{-~、。・「」『』（）〜ー…！？＿]/g, "");
  return t;
}

/**
 * 使えない言葉が含まれていたら true を返します。
 * どの言葉だったかは返しません（本人に伝えると、かえって
 * 抜け道探しを促してしまうため）。
 */
export function containsNgWord(text) {
  let t = normalize(text);
  if (!t) return false;

  // 先に「安全な言葉」を取り除く
  for (const safe of SAFE_WORDS) {
    const s = normalize(safe);
    if (s) t = t.split(s).join("");
  }

  for (const word of NG_WORDS) {
    const w = normalize(word);
    if (w && t.includes(w)) return true;
  }
  return false;
}
