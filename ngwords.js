/** カタカナをひらがなに直す */
function kataToHira(s) {
  return s.replace(/[ァ-ヶ]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) - 0x60)
  );
}

/**
 * 比べやすい形に整える。
 *  ・全角英数字・半角カナを標準の形に（normalize("NFKC")）
 *  ・英字は小文字に
 *  ・カタカナをひらがなに
 *  ・数字で字を装った崩しを戻す（0→o, 1→i, 3→e …）
 *  ・空白・記号・伸ばし棒をすべて取り除く
 */
function normalize(s) {
  let t = String(s ?? "").normalize("NFKC").toLowerCase();
  t = kataToHira(t);
  t = t
    .replace(/0/g, "o").replace(/1/g, "i").replace(/3/g, "e")
    .replace(/4/g, "a").replace(/5/g, "s").replace(/7/g, "t")
    .replace(/@/g, "a").replace(/\$/g, "s");
  // ひらがな・漢字・英数字だけ残す
  t = t.replace(/[^0-9a-zぁ-ん一-龥]/g, "");
  return t;
}

/** 同じ字の連続を1つにまとめる（「しねぇぇぇ」「fuuuck」対策）*/
function collapse(t) {
  return t.replace(/(.)\1+/g, "$1");
}

/** 安全な言葉をあらかじめ取り除く */
function stripSafe(t) {
  for (const safe of SAFE_WORDS) {
    const s = normalize(safe);
    if (s) t = t.split(s).join("");
  }
  return t;
}

/**
 * 使えない言葉が含まれていたら true を返します。
 * どの言葉だったかは返しません（本人に伝えると、かえって
 * 抜け道探しを促してしまうため）。
 */
export function containsNgWord(text) {
  const base = stripSafe(normalize(text));
  if (!base) return false;

  // そのままの形と、連続をまとめた形の両方で調べます
  const targets = [base, stripSafe(collapse(base))];

  for (const word of NG_WORDS) {
    const w = normalize(word);
    if (!w) continue;
    if (targets.some((t) => t.includes(w))) return true;
  }
  return false;
}
